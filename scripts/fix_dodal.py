# -*- coding: utf-8 -*-
"""도달δ예측을 근사(√r)에서 정확식으로 다시 계산함 (10/12).

왜 —
  근사  도달δ = 내 보정후   − 빔문턱 × 내 분모 ÷ √r
  정확  도달δ = 부모 보정후 − 빔문턱 × 부모 분모 ÷ r

  근사는 "부모 분모 = 내 분모 × √r" 을 가정하는데, 이 데이터에서 분모는 1/√N 으로 줄지
  않음 (log-log 기울기 2일 −0.373 / 14일 −0.310). 기준선 오차에 N 과 무관한 바닥이 있어서임.
  그래서 근사는 부모를 실제보다 민감하게 봐 도달δ 를 작게 잡음.

  부모(단일 조건)의 보정후·분모는 9-1 이 이미 results/무주입_조건_{창}.csv 에 저장해 뒀으므로
  근사할 필요가 없음. 빔 서치를 다시 돌리지 않으므로 1분도 안 걸림.

  정확식이 쓰는 유일한 사실 — 자식 평가행의 δ% 를 뒤집으면 부모 평균 편차가 정확히 δ×r
  만큼 내려감 (뒤집은 행 수 ÷ 부모 행 수 = δ × r). 이건 근사가 아니라 등식임.

고치는 것
  results/쌍_조용_{창}.csv          도달δ예측·예측하한·무엇에막히나 를 정확식으로 **덮어씀**
                                    (근사값은 도달δ예측_근사 로 남김)
  results/찾음하한_2조건_{창}.csv    도달δ예측_정확·막힘_정확 을 **덧붙임**
                                    (원래 칸은 그때 탐색을 어떻게 돌렸는지의 기록이라 안 건드림)

원본은 results/백업_20261012/ 로 복사해 둠.

쓰는 법:  python scripts/fix_dodal.py
"""
import os
import shutil

import numpy as np
import pandas as pd

RES = 'results'
백업 = os.path.join(RES, '백업_20261012')
os.makedirs(백업, exist_ok=True)


def 부모표(창):
    """단일 조건 264개의 보정후·분모·평가행. 14일 파일은 중복 26개가 있어 걸러냄"""
    표 = pd.read_csv(os.path.join(RES, '무주입_조건_{}.csv'.format(창)), encoding='utf-8-sig')
    전체 = len(표)
    표 = 표.drop_duplicates('이름')
    # 빔 문턱 — 1단계에서 빔 20칸에 들려면 필요한 t. 9-5 와 같은 방식으로 뽑음
    문턱 = 표['t'].nsmallest(20).iloc[-1]
    print('[{}] 조건 {}개 (중복 {}개 제외) / 빔 20칸 문턱 t = {:.3f}'.format(
        창, len(표), 전체 - len(표), 문턱))
    return 표.set_index('이름'), 문턱


def 도달정확(부모, 문턱, 자식평가행, 이름들):
    """부모를 직접 채점한 값으로 도달δ 를 구함. 두 부모 중 싼 쪽(= 먼저 빔에 드는 쪽).

       돌려주는 것 — (도달δ, 이미빔안)
       도달δ 가 음수로 나오면 부모가 주입 전에 이미 빔 20칸 안에 있다는 뜻이라 0 으로 둠"""
    값들 = []
    for 이름 in 이름들:
        if 이름 not in 부모.index:
            continue
        부 = 부모.loc[이름]
        r = 자식평가행 / 부['평가행']
        값들.append((부['보정후'] - 문턱 * 부['분모']) / r)
    if not 값들:
        return np.nan, False
    싼쪽 = min(값들)
    return max(싼쪽, 0.0), 싼쪽 <= 0


for 창 in ['2일', '14일']:
    print('\n' + '=' * 70)
    부모, 문턱 = 부모표(창)

    # ── 쌍_조용 — 예측 표이므로 덮어씀 ────────────────────────────────
    경로 = os.path.join(RES, '쌍_조용_{}.csv'.format(창))
    if os.path.exists(경로):
        shutil.copy2(경로, os.path.join(백업, os.path.basename(경로)))
        표 = pd.read_csv(경로, encoding='utf-8-sig')
        정확, 이미 = [], []
        for _, x in 표.iterrows():
            a, b = 도달정확(부모, 문턱, x['평가행'], [x['A'], x['B']])
            정확.append(a)
            이미.append(b)
        표['도달δ예측_근사'] = 표['도달δ예측']
        표['도달δ예측'] = 정확
        표['부모이미빔안'] = 이미
        표['예측하한'] = 표[['보고δ예측', '도달δ예측']].max(axis=1)
        표['무엇에막히나'] = np.where(표['도달δ예측'] > 표['보고δ예측'], '도달(빔)', '보고(판정선)')
        표.to_csv(경로, index=False, encoding='utf-8-sig')
        옛막힘 = (표['도달δ예측_근사'] > 표['보고δ예측']).sum()
        새막힘 = (표['무엇에막히나'] == '도달(빔)').sum()
        print('쌍_조용 {:,}쌍 — 도달에 막힌다고 본 쌍 {:,}개(근사) → {:,}개(정확) / '
              '부모가 이미 빔 안인 쌍 {:,}개'.format(len(표), 옛막힘, 새막힘, 표['부모이미빔안'].sum()))

    # ── 찾음하한 — 실행 기록이므로 칸을 덧붙이기만 함 ──────────────────
    경로 = os.path.join(RES, '찾음하한_2조건_{}.csv'.format(창))
    if not os.path.exists(경로):
        continue
    shutil.copy2(경로, os.path.join(백업, os.path.basename(경로)))
    표 = pd.read_csv(경로, encoding='utf-8-sig')
    정확, 이미 = [], []
    for _, x in 표.iterrows():
        a, b = 도달정확(부모, 문턱, x['평가행'], [x['A'], x['B']])
        정확.append(a)
        이미.append(b)
    표['도달δ예측_정확'] = 정확
    표['부모이미빔안'] = 이미
    표['막힘_정확'] = np.where(표['도달δ예측_정확'] > 표['보고δ예측'], '도달(빔)', '보고(판정선)')
    표.to_csv(경로, index=False, encoding='utf-8-sig')

    옛막힘 = (표['도달δ예측'] > 표['보고δ예측']).sum()
    새막힘 = (표['막힘_정확'] == '도달(빔)').sum()
    print('찾음하한 {}개 — 도달에 막힘 {}개(근사) → {}개(정확) / 부모가 이미 빔 안 {}개'.format(
        len(표), 옛막힘, 새막힘, 표['부모이미빔안'].sum()))
    표['정확÷근사'] = 표['도달δ예측_정확'] / 표['도달δ예측']
    print(표[['A', 'B', '희석r', '보고δ예측', '도달δ예측', '도달δ예측_정확',
             '막힘_정확', '찾음하한']].round(3).to_string(index=False))

print('\n원본은 {} 에 복사해 뒀음'.format(백업))
